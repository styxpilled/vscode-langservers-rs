// Writes the upstream built-in HTML data (`webCustomData.ts`) as JSON and the
// entity table (`htmlEntities.ts`) as Rust.
// Usage: node gen-data.mjs <vscode-html-languageservice dir> <crate src dir>
import fs from 'fs';
import path from 'path';
import url from 'url';

const [root, out] = process.argv.slice(2);
const lib = url.pathToFileURL(path.resolve(root, 'lib/esm')).href;
const { htmlData } = await import(`${lib}/languageFacts/data/webCustomData.js`);
fs.mkdirSync(path.join(out, 'data'), { recursive: true });
fs.writeFileSync(path.join(out, 'data/html5.json'), JSON.stringify(htmlData));

const { entities } = await import(`${lib}/parser/htmlEntities.js`);
const escape = (v) => [...v].map((c) => `\\u{${c.codePointAt(0).toString(16)}}`).join('');
const rows = Object.entries(entities).map(([k, v]) => `    (${JSON.stringify(k)}, "${escape(v)}"),`);
fs.writeFileSync(path.join(out, 'parser/entities.rs'), `//! Generated by \`scripts/html/gen-data.mjs\` from \`htmlEntities.ts\`, in the
//! key order of the upstream object.

pub static ENTITIES: &[(&str, &str)] = &[
${rows.join('\n')}
];
`);
