// The texts of the HTML sweeps: the upstream test texts, the VS Code server
// test fixtures and the lists below.
import fs from "fs";
import path from "path";

export function sweepTexts(fixture, vscode, extra) {
	const texts = new Set();
	const f = JSON.parse(fs.readFileSync(fixture, "utf8"));
	for (const p of f.parser) texts.add(p.text);
	for (const c of f.calls) texts.add(c.document.text);
	const fixtures = path.join(vscode, "extensions/html-language-features/server/src/test");
	for (const dir of ["fixtures/inputs", "fixtures/expected", "pathCompletionFixtures", "pathCompletionFixtures/about"]) {
		for (const name of fs.readdirSync(path.join(fixtures, dir)).filter((n) => n.endsWith(".html"))) {
			texts.add(fs.readFileSync(path.join(fixtures, dir, name), "utf8"));
		}
	}
	for (const t of extra) texts.add(t);
	return [...texts];
}

