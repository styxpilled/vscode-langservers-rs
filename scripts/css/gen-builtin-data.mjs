// Writes the tables of `builtinData.ts` and `colors.ts` as Rust source.
// Usage: node gen-builtin-data.mjs <vscode-css-languageservice dir> <crate src dir>
import fs from 'fs';
import path from 'path';
import url from 'url';

const [root, srcDir] = process.argv.slice(2);
const lib = url.pathToFileURL(path.resolve(root, 'lib/esm/languageFacts')).href;
const builtin = await import(`${lib}/builtinData.js`);
const colors = await import(`${lib}/colors.js`);

const str = (s) => JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, '\\u{$1}');
const snake = (s) => s.replace(/([A-Z])/g, '_$1').toUpperCase();

function table(name, value) {
	const id = snake(name);
	if (Array.isArray(value)) {
		return `pub const ${id}: &[&str] = &[\n${value.map((v) => `    ${str(v)},\n`).join('')}];\n`;
	}
	const entries = Object.entries(value);
	if (Array.isArray(entries[0][1])) {
		const rows = entries.map(([k, v]) => `    (${str(k)}, &[${v.map(str).join(', ')}]),\n`).join('');
		return `pub const ${id}: &[(&str, &[&str])] = &[\n${rows}];\n`;
	}
	return `pub const ${id}: &[(&str, &str)] = &[\n${entries.map(([k, v]) => `    (${str(k)}, ${str(v)}),\n`).join('')}];\n`;
}

const header = (file) => `//! Tables of \`${file}\`. Generated by \`scripts/css/gen-builtin-data.mjs\`.\n\n`;

const src = fs.readFileSync(path.resolve(root, 'src/languageFacts/builtinData.ts'), 'utf8');
const names = [...src.matchAll(/^export const (\w+)/gm)].map((m) => m[1]);
fs.writeFileSync(path.join(srcDir, 'builtin_data.rs'), header('builtinData.ts') + names.map((n) => table(n, builtin[n])).join('\n'));

const fns = colors.colorFunctions.map((f) => `    ColorFunction {\n        label: ${str(f.label)},\n        func: ${str(f.func)},\n        insert_text: ${str(f.insertText)},\n        desc: ${str(f.desc)},\n    },\n`).join('');
fs.writeFileSync(path.join(srcDir, 'color_data.rs'), header('colors.ts') +
	'use super::colors::ColorFunction;\n\n' +
	`pub const COLOR_FUNCTIONS: &[ColorFunction] = &[\n${fns}];\n\n` +
	table('colors', colors.colors) + '\n' + table('colorKeywords', colors.colorKeywords));
